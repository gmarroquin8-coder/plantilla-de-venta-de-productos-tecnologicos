const assert = require("node:assert/strict");
const { randomUUID } = require("node:crypto");
const { after, before, test } = require("node:test");
const { Pool } = require("pg");
const { bootstrapAdmin, createApp, initializeDatabase } = require("../server");

const schema = `test_${randomUUID().replace(/-/g, "")}`;
const databaseConfig = {
  host: process.env.PGHOST || "127.0.0.1",
  port: Number(process.env.PGPORT || 5432),
  database: process.env.PGDATABASE,
  user: process.env.PGUSER,
  password: process.env.PGPASSWORD
};
const testSecret = "voltio-test-secret-with-at-least-32-bytes";
let adminPool;
let pool;
let server;
let baseUrl;

async function request(path, { method = "GET", json, cookie, origin = baseUrl } = {}) {
  const headers = {};
  if (json !== undefined) headers["Content-Type"] = "application/json";
  if (method !== "GET") headers.Origin = origin;
  if (cookie) headers.Cookie = cookie;

  const response = await fetch(`${baseUrl}${path}`, {
    method,
    headers,
    body: json === undefined ? undefined : JSON.stringify(json)
  });
  const responseText = response.status === 204 ? "" : await response.text();
  const body = responseText ? JSON.parse(responseText) : null;
  return { response, body };
}

async function register(email, password = "correct horse battery") {
  const result = await request("/api/auth/register", {
    method: "POST",
    json: { name: "Voltio Test", email, password }
  });
  const setCookie = result.response.headers.get("set-cookie");
  return {
    ...result,
    cookie: setCookie ? setCookie.split(";")[0] : null
  };
}

before(async () => {
  if (!databaseConfig.database || !databaseConfig.user || !databaseConfig.password) {
    throw new Error("PostgreSQL connection variables are required for API integration tests.");
  }

  adminPool = new Pool(databaseConfig);
  await adminPool.query(`CREATE SCHEMA "${schema}"`);
  pool = new Pool({
    ...databaseConfig,
    options: `-c search_path=${schema}`
  });
  await pool.query(
    `CREATE TABLE users (
       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
       name VARCHAR(100) NOT NULL,
       email VARCHAR(254) NOT NULL UNIQUE,
       password_hash TEXT NOT NULL,
       created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
     )`
  );
  await pool.query(
    `INSERT INTO users (name, email, password_hash)
     VALUES ('Existing customer', 'existing.customer@example.invalid', 'preserved-hash')`
  );
  await initializeDatabase(pool);

  const app = createApp({
    pool,
    jwtSecret: testSecret,
    secureCookie: true,
    authLimit: 100
  });
  server = app.listen(0, "127.0.0.1");
  await new Promise((resolve, reject) => {
    server.once("listening", resolve);
    server.once("error", reject);
  });
  baseUrl = `http://127.0.0.1:${server.address().port}`;
});

after(async () => {
  if (server) await new Promise((resolve) => server.close(resolve));
  if (pool) await pool.end();
  if (adminPool) {
    await adminPool.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
    await adminPool.end();
  }
});

test("catalog returns persisted products and illustrative stock", async () => {
  const { response, body } = await request("/api/catalog");
  assert.equal(response.status, 200);
  assert.equal(body.categories.length, 10);
  assert.equal(body.categories.reduce((total, category) => total + category.products.length, 0), 150);
  const appliances = body.categories.find((category) => category.id === "electrodomesticos");
  const coffeeMaker = appliances.products.find((product) => product.id === "cafetera");
  assert.equal(coffeeMaker.stock, 20);
});

test("database initialization is additive and does not reset managed stock", async () => {
  await pool.query("UPDATE products SET stock = 7 WHERE id = $1", ["mouse"]);
  await initializeDatabase(pool);
  const { rows } = await pool.query("SELECT stock FROM products WHERE id = $1", ["mouse"]);
  assert.equal(rows[0].stock, 7);
  const { rows: users } = await pool.query(
    "SELECT name, email, password_hash, role FROM users WHERE email = $1",
    ["existing.customer@example.invalid"]
  );
  assert.deepEqual(users[0], {
    name: "Existing customer",
    email: "existing.customer@example.invalid",
    password_hash: "preserved-hash",
    role: "customer"
  });
});

test("registration validates input, creates a secure session, and normalizes email", async () => {
  const invalid = await register("short-password@example.invalid", "short");
  assert.equal(invalid.response.status, 400);

  const created = await register("Test.User@example.invalid");
  assert.equal(created.response.status, 201);
  assert.equal(created.body.user.email, "test.user@example.invalid");
  assert.equal("password_hash" in created.body.user, false);
  assert.match(created.response.headers.get("set-cookie"), /HttpOnly/i);
  assert.match(created.response.headers.get("set-cookie"), /Secure/i);
  assert.match(created.response.headers.get("set-cookie"), /SameSite=Lax/i);

  await initializeDatabase(pool);
  const currentUser = await request("/api/auth/me", { cookie: created.cookie });
  assert.equal(currentUser.response.status, 200);
  assert.equal(currentUser.body.user.email, "test.user@example.invalid");

  const login = await request("/api/auth/login", {
    method: "POST",
    json: { email: " TEST.USER@EXAMPLE.INVALID ", password: "correct horse battery" }
  });
  assert.equal(login.response.status, 200);
  assert.equal(login.body.user.email, "test.user@example.invalid");

  const wrongPassword = await request("/api/auth/login", {
    method: "POST",
    json: { email: "test.user@example.invalid", password: "incorrect password" }
  });
  assert.equal(wrongPassword.response.status, 401);

  const duplicate = await register("TEST.USER@example.invalid");
  assert.equal(duplicate.response.status, 409);

  const wrongOrigin = await request("/api/auth/logout", {
    method: "POST",
    cookie: created.cookie,
    origin: "https://attacker.example"
  });
  assert.equal(wrongOrigin.response.status, 403);
});

test("orders require a session, store server-calculated totals, reserve stock, and stay user-scoped", async () => {
  const unauthenticated = await request("/api/orders", {
    method: "POST",
    json: { items: [{ productId: "cafetera", quantity: 1 }] }
  });
  assert.equal(unauthenticated.response.status, 401);

  const owner = await register("order.owner@example.invalid");
  assert.equal(owner.response.status, 201);
  const order = await request("/api/orders", {
    method: "POST",
    cookie: owner.cookie,
    json: {
      name: "Voltio Order Owner",
      phone: "555 123 4567",
      address: "Calle de prueba 123, Ciudad de México",
      items: [{ productId: "cafetera", quantity: 2, unitPrice: 1, userId: "other-user" }]
    }
  });

  assert.equal(order.response.status, 201);
  assert.equal(order.body.order.status, "pending");
  assert.equal(order.body.order.total, 3798);
  assert.equal(order.body.order.items[0].unitPrice, 1899);
  assert.equal(order.body.order.items[0].stock, 18);

  const concurrentOrders = await Promise.all([1, 2].map(() => request("/api/orders", {
    method: "POST",
    cookie: owner.cookie,
    json: {
      name: "Voltio Order Owner",
      phone: "555 123 4567",
      address: "Calle de prueba 123, Ciudad de México",
      items: [{ productId: "cafetera", quantity: 10 }]
    }
  })));
  assert.deepEqual(
    concurrentOrders.map(({ response }) => response.status).sort(),
    [201, 409]
  );

  const history = await request("/api/orders", { cookie: owner.cookie });
  assert.equal(history.response.status, 200);
  assert.equal(history.body.orders.length, 2);
  assert.ok(history.body.orders.some((entry) => entry.id === order.body.order.id));

  const otherUser = await register("order.other@example.invalid");
  const otherHistory = await request("/api/orders", { cookie: otherUser.cookie });
  assert.equal(otherHistory.response.status, 200);
  assert.deepEqual(otherHistory.body.orders, []);

  const unavailable = await request("/api/orders", {
    method: "POST",
    cookie: owner.cookie,
    json: {
      name: "Voltio Order Owner",
      phone: "555 123 4567",
      address: "Calle de prueba 123, Ciudad de México",
      items: [
        { productId: "cafetera", quantity: 1 },
        { productId: "mouse", quantity: 99 }
      ]
    }
  });
  assert.equal(unavailable.response.status, 409);

  const unchangedHistory = await request("/api/orders", { cookie: owner.cookie });
  assert.equal(unchangedHistory.body.orders.length, 2);
  const unchangedCatalog = await request("/api/catalog");
  const appliances = unchangedCatalog.body.categories.find((category) => category.id === "electrodomesticos");
  const coffeeMaker = appliances.products.find((product) => product.id === "cafetera");
  assert.equal(coffeeMaker.stock, 8);
});

test("logout clears the session cookie", async () => {
  const user = await register("logout.user@example.invalid");
  const loggedOut = await request("/api/auth/logout", {
    method: "POST",
    cookie: user.cookie
  });
  assert.equal(loggedOut.response.status, 204);
  assert.match(loggedOut.response.headers.get("set-cookie"), /Expires=Thu, 01 Jan 1970/i);

  const currentUser = await request("/api/auth/me");
  assert.equal(currentUser.response.status, 401);
});

test("admin bootstrap promotes the configured account without resetting its password", async () => {
  const first = await bootstrapAdmin(
    pool,
    "store.admin@example.invalid",
    "initial admin password"
  );
  assert.equal(first.role, "admin");

  const second = await bootstrapAdmin(
    pool,
    "STORE.ADMIN@example.invalid",
    "replacement password is ignored"
  );
  assert.equal(second.id, first.id);

  const oldPassword = await request("/api/auth/login", {
    method: "POST",
    json: { email: "store.admin@example.invalid", password: "initial admin password" }
  });
  assert.equal(oldPassword.response.status, 200);
  assert.equal(oldPassword.body.user.role, "admin");

  const replacementPassword = await request("/api/auth/login", {
    method: "POST",
    json: { email: "store.admin@example.invalid", password: "replacement password is ignored" }
  });
  assert.equal(replacementPassword.response.status, 401);
});

test("only admins can create, edit, list, and soft-delete products", async () => {
  const anonymousList = await request("/api/admin/products");
  assert.equal(anonymousList.response.status, 401);
  const anonymousAdminCheck = await request("/api/admin/check");
  assert.equal(anonymousAdminCheck.response.status, 401);

  const customerResult = await request("/api/auth/register", {
    method: "POST",
    json: {
      name: "Voltio Customer",
      email: "product.customer@example.invalid",
      password: "correct horse battery",
      role: "admin"
    }
  });
  const customer = {
    ...customerResult,
    cookie: customerResult.response.headers.get("set-cookie").split(";")[0]
  };
  assert.equal(customer.body.user.role, "customer");
  const customerAdminCheck = await request("/api/admin/check", { cookie: customer.cookie });
  assert.equal(customerAdminCheck.response.status, 403);
  const forbiddenList = await request("/api/admin/products", { cookie: customer.cookie });
  assert.equal(forbiddenList.response.status, 403);

  const forbiddenCreate = await request("/api/admin/products", {
    method: "POST",
    cookie: customer.cookie,
    json: {
      id: "customer-product",
      categoryId: "computacion",
      name: "No autorizado",
      emoji: "🚫",
      description: "El usuario no debe poder crear productos.",
      price: 100,
      badge: "",
      rating: 0,
      reviews: 0,
      stock: 1
    }
  });
  assert.equal(forbiddenCreate.response.status, 403);
  for (const method of ["PUT", "DELETE"]) {
    const forbiddenMutation = await request("/api/admin/products/mouse", {
      method,
      cookie: customer.cookie,
      json: method === "PUT" ? {
        id: "mouse",
        categoryId: "computacion",
        name: "No autorizado",
        emoji: "🚫",
        description: "El usuario no debe poder editar productos.",
        price: 1,
        badge: "",
        rating: 0,
        reviews: 0,
        stock: 1
      } : undefined
    });
    assert.equal(forbiddenMutation.response.status, 403);
  }

  const bootstrap = await bootstrapAdmin(
    pool,
    "product.admin@example.invalid",
    "secure initial admin password"
  );
  assert.equal(bootstrap.role, "admin");
  const adminLogin = await request("/api/auth/login", {
    method: "POST",
    json: {
      email: "product.admin@example.invalid",
      password: "secure initial admin password"
    }
  });
  assert.equal(adminLogin.response.status, 200);
  assert.equal(adminLogin.body.user.role, "admin");
  const adminCookie = adminLogin.response.headers.get("set-cookie").split(";")[0];
  const authorizedAdminCheck = await request("/api/admin/check", { cookie: adminCookie });
  assert.equal(authorizedAdminCheck.response.status, 204);

  const newProduct = {
    id: "voltio-test-device",
    categoryId: "computacion",
    name: "Dispositivo de prueba",
    emoji: "🧪",
    description: "Producto temporal para validar el CRUD de administración.",
    price: 875,
    badge: "Prueba",
    rating: 4.5,
    reviews: 12,
    stock: 9
  };
  const created = await request("/api/admin/products", {
    method: "POST",
    cookie: adminCookie,
    json: newProduct
  });
  assert.equal(created.response.status, 201);
  assert.equal(created.body.product.id, newProduct.id);
  assert.equal(created.body.product.stock, 9);
  const wrongOrigin = await request("/api/admin/products", {
    method: "POST",
    cookie: adminCookie,
    origin: "https://attacker.example",
    json: { ...newProduct, id: "wrong-origin-product" }
  });
  assert.equal(wrongOrigin.response.status, 403);

  const invalid = await request("/api/admin/products", {
    method: "POST",
    cookie: adminCookie,
    json: { ...newProduct, id: "invalid slug!" }
  });
  assert.equal(invalid.response.status, 400);

  const listed = await request("/api/admin/products", { cookie: adminCookie });
  assert.equal(listed.response.status, 200);
  assert.ok(listed.body.products.some((product) => product.id === newProduct.id));

  const updated = await request(`/api/admin/products/${newProduct.id}`, {
    method: "PUT",
    cookie: adminCookie,
    json: { ...newProduct, name: "Dispositivo actualizado", price: 975, stock: 15 }
  });
  assert.equal(updated.response.status, 200);
  assert.equal(updated.body.product.name, "Dispositivo actualizado");
  assert.equal(updated.body.product.price, 975);

  const deleted = await request(`/api/admin/products/${newProduct.id}`, {
    method: "DELETE",
    cookie: adminCookie
  });
  assert.equal(deleted.response.status, 204);

  const hiddenFromCatalog = await request("/api/catalog");
  const computers = hiddenFromCatalog.body.categories.find((category) => category.id === "computacion");
  assert.equal(computers.products.some((product) => product.id === newProduct.id), false);
});
